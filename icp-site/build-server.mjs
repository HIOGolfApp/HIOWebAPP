// Server build: server/index.ts + src/app/api/** -> dist/server.mjs, one self-contained ES module.
// The original code imports `cloudflare:workers` (env.DB) and `next/headers` (headers/cookies);
// those resolve to server/shims/*, so the route files run unchanged on plain Node.
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const shims = {
  'cloudflare:workers': here('./server/shims/cloudflare-workers.ts'),
  'next/headers': here('./server/shims/next-headers.ts'),
};

await build({
  entryPoints: [here('./server/index.ts')],
  outfile: here('./dist/server.mjs'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  loader: { '.sql': 'text' },
  legalComments: 'none',
  logLevel: 'warning',
  banner: { js: '// Generated by icp-site/build-server.mjs from icp-site/server and icp-site/src. Do not edit; run `npm run build`.' },
  plugins: [{
    name: 'shims',
    setup(b) {
      b.onResolve({ filter: /^(cloudflare:workers|next\/headers)$/ }, (args) => ({ path: shims[args.path] }));
    },
  }],
});
console.log('built dist/server.mjs');
